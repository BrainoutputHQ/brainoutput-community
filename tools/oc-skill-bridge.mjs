// SKILL BRIDGE — make Paperclip's company_skills actually reachable by an OpenCode agent.
//
// Paperclip's own sync is broken for the opencode-local adapter, in two independent ways. Both
// were proven empirically against a live `opencode serve` 1.18.7; either alone is fatal, which is
// why `POST /agents/:id/skills/sync` returns 200 and delivers nothing:
//
//   1. WRONG DIRECTORY. The adapter writes to `$HOME/.claude/skills` (Claude Code's convention).
//      OpenCode never reads that path. It discovers skills in `<project>/.opencode/skill[s]/` and
//      `$XDG_CONFIG_HOME/opencode/skill[s]/` — verified by planting probes in all four and asking
//      the server which it could see.
//   2. NO FRONTMATTER. Paperclip writes SKILL.md starting at the first heading. OpenCode requires
//      YAML frontmatter with `name` and `description`. Placed in the CORRECT directory, unmodified
//      Paperclip skills were still invisible; adding frontmatter made them appear immediately.
//
// This bridge reads Paperclip's skill store and re-emits each selected skill in the form OpenCode
// actually loads. The `description` matters more than it looks: OpenCode uses it for progressive
// disclosure — the model reads descriptions and pulls in a skill body only when it judges the
// skill relevant. A vague description means the skill is never opened.
//
// Usage:
//   node tools/oc-skill-bridge.mjs --store <paperclip-skills-dir> --into <repo-or-worktree>
//                                  [--skills a,b,c] [--api http://127.0.0.1:3220 --company <id>]
//
// --into <dir> receives <dir>/.opencode/skill/<name>/SKILL.md
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync, rmSync } from "node:fs";
import { join } from "node:path";

const argv = process.argv.slice(2);
const arg = (n, d = null) => { const i = argv.indexOf(`--${n}`); return i >= 0 && argv[i + 1] && !argv[i + 1].startsWith("--") ? argv[i + 1] : d; };

const STORE = arg("store");
const INTO = arg("into");
const ONLY = (arg("skills") || "").split(",").map((s) => s.trim()).filter(Boolean);
const API = arg("api");
const COMPANY = arg("company");
// `--into-agents-md <file>` inlines the skills into an agent's instructions bundle instead of
// writing .opencode/skill/. Chosen deliberately over the "supported" path: OpenCode skills are
// PROGRESSIVE — the model sees name+description and opens the body only if it decides to. In a
// controlled A/B (same agent, same task, skills present in one repo only) the agent with the
// skills available never opened them and hit the very trap the first section documents. An
// AGENTS.md rule, by contrast, demonstrably changed behaviour on the next run.
// Always-on costs prompt space; optional costs everything when it is not taken.
const AGENTS_MD = arg("into-agents-md");
const MAX_INLINE_BYTES = Number(arg("max-bytes", "24000"));
const BEGIN = "<!-- BEGIN company-skills (generated by tools/oc-skill-bridge.mjs — do not edit by hand) -->";
const END = "<!-- END company-skills -->";

if (!STORE || (!INTO && !AGENTS_MD)) {
  console.error("usage: --store <dir> (--into <repo> | --into-agents-md <AGENTS.md>) [--skills a,b] [--api URL --company ID]");
  process.exit(2);
}
if (!existsSync(STORE)) { console.error(`skill store not found: ${STORE}`); process.exit(2); }

// Descriptions live in the DB, not on disk — fetch them when we can. Without a good description a
// skill is dead weight: OpenCode will list it and the model will never open it.
let meta = {};
if (API && COMPANY) {
  try {
    const res = await fetch(`${API}/api/companies/${COMPANY}/skills`, { signal: AbortSignal.timeout(10000) });
    // The skills endpoint returns a BARE ARRAY, unlike most of this API which wraps in {data}.
    // Assuming the wrapped shape silently yields zero metadata and every skill falls back to a
    // useless auto-description — which disables progressive disclosure without any error.
    const payload = await res.json();
    const rows = Array.isArray(payload) ? payload : (payload?.data ?? []);
    for (const s of rows) if (s.slug) meta[s.slug] = { description: s.description || s.tagline || "", name: s.name || s.slug };
  } catch (e) { console.error(`warning: could not read skill metadata from the API (${e.message}); falling back to on-disk only`); }
}

const names = readdirSync(STORE, { withFileTypes: true })
  .filter((d) => d.isDirectory() && !d.name.startsWith("__"))
  .map((d) => d.name)
  .filter((n) => !ONLY.length || ONLY.includes(n));

if (!names.length) { console.error(`no skills matched in ${STORE}`); process.exit(1); }

if (AGENTS_MD) {
  if (!existsSync(AGENTS_MD)) { console.error(`instructions file not found: ${AGENTS_MD}`); process.exit(2); }
  const parts = [];
  for (const name of names) {
    const src = join(STORE, name, "SKILL.md");
    if (!existsSync(src)) { console.error(`  skip ${name}: no SKILL.md`); continue; }
    const body = readFileSync(src, "utf8").replace(/^---\s*\n[\s\S]*?\n---\s*\n/, "").trim();
    const when = (meta[name]?.description || "").replace(/\s+/g, " ").trim();
    // Demote headings one level so a skill's `#` cannot outrank the instruction file's structure.
    const demoted = body.replace(/^(#{1,5}) /gm, "#$1 ");
    parts.push(`### ${name}\n${when ? `_When this applies: ${when}_\n` : ""}\n${demoted}`);
  }
  const block = `${BEGIN}\n\n## Standing knowledge — these are established facts, not suggestions\n\n` +
    `The sections below are company skills inlined into your instructions. They record things that are\n` +
    `already known to be true and that are easy to get wrong. Follow them; do not re-derive them.\n\n` +
    parts.join("\n\n---\n\n") + `\n\n${END}`;
  if (Buffer.byteLength(block) > MAX_INLINE_BYTES) {
    console.error(`refusing: inlined skills are ${Buffer.byteLength(block)} bytes (cap ${MAX_INLINE_BYTES}).`);
    console.error("AGENTS.md is prompt-resident on EVERY call — an unbounded bundle taxes every run.");
    console.error("Trim a skill, or raise --max-bytes deliberately.");
    process.exit(1);
  }
  let cur = readFileSync(AGENTS_MD, "utf8");
  const b = cur.indexOf(BEGIN), e = cur.indexOf(END);
  cur = (b >= 0 && e > b) ? cur.slice(0, b) + block + cur.slice(e + END.length) : `${cur.trimEnd()}\n\n${block}\n`;
  writeFileSync(AGENTS_MD, cur);
  console.log(`  inlined ${parts.length} skill(s), ${Buffer.byteLength(block)} bytes -> ${AGENTS_MD}`);
  process.exit(parts.length ? 0 : 1);
}

const target = join(INTO, ".opencode", "skill");
rmSync(target, { recursive: true, force: true });   // idempotent: never leave a stale skill behind
mkdirSync(target, { recursive: true });

let written = 0;
for (const name of names) {
  const src = join(STORE, name, "SKILL.md");
  if (!existsSync(src)) { console.error(`  skip ${name}: no SKILL.md`); continue; }
  const body = readFileSync(src, "utf8");
  if (/^---\s*\n/.test(body)) { console.error(`  skip ${name}: already has frontmatter (unexpected — not rewriting)`); continue; }

  const m = meta[name] || {};
  // Fall back to the first heading, then the first prose line — a missing description is worse
  // than an imperfect one, because it silently disables progressive disclosure.
  const heading = (body.match(/^#\s+(.+)$/m) || [])[1];
  const firstProse = body.split("\n").find((l) => l.trim() && !l.startsWith("#") && !l.startsWith("---"));
  const description = (m.description || firstProse || heading || name).replace(/\s+/g, " ").trim().slice(0, 300);

  mkdirSync(join(target, name), { recursive: true });
  writeFileSync(join(target, name, "SKILL.md"),
    `---\nname: ${name}\ndescription: ${description}\n---\n\n${body}`);
  console.log(`  wrote ${name}  (${description.slice(0, 70)}${description.length > 70 ? "…" : ""})`);
  written++;
}

console.log(`\n${written} skill(s) -> ${target}`);
console.log("NOTE: .opencode/ must be gitignored in the target repo, or an agent will commit it.");
process.exit(written ? 0 : 1);
